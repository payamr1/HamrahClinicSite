-- ============================================================
--  همراه کلینیک — حذف‌ها
--
--  این فایل وضعیت فعلی را اصلاح می‌کند. ردیف‌های دو پزشک از
--  02 برداشته شد، ولی دیتابیسی که قبلاً import شده آن‌ها را
--  دارد و با نبودنشان در فایل، خودبه‌خود پاک نمی‌شوند. پس
--  حذفشان باید صریح باشد.
--
--  اجرای مکرر بی‌خطر است: هر دستور یا چیزی برای حذف پیدا
--  می‌کند یا هیچ.
-- ============================================================
SET NAMES utf8mb4;

-- ------------------------------------------------------------
--  تگ‌های رسانه
--
--  entity_id در media_tag چندریختی است و کلید خارجی ندارد، پس
--  با حذف پزشک خودبه‌خود پاک نمی‌شود. اول پاک می‌شود، وگرنه
--  شناسه‌اش بعداً به پزشک دیگری می‌خورد.
-- ------------------------------------------------------------
DELETE mt FROM media_tag mt
  JOIN doctors d ON d.id = mt.entity_id
 WHERE mt.entity_type = 'doctor'
   AND d.name IN ('دکتر مهدی شفیعی ثابت', 'دکتر مریم اسلامی');

-- ------------------------------------------------------------
--  خود پزشکان
--  doctor_clinic با ON DELETE CASCADE پاک می‌شود.
-- ------------------------------------------------------------
DELETE FROM doctors
 WHERE name IN ('دکتر مهدی شفیعی ثابت', 'دکتر مریم اسلامی');

-- صفحه‌ی پروفایلشان. این دو آدرس تازه بودند و هرگز ایندکس
-- نشدند، پس حذفشان بدهی سئویی ندارد.
DELETE FROM pages
 WHERE path IN ('/team/دکتر-مهدی-شفیعی-ثابت/', '/team/دکتر-مریم-اسلامی/');

-- ------------------------------------------------------------
--  بخش مغز و اعصاب
--
--  این بخش فقط برای دکتر شفیعی ثابت ساخته شده بود و با رفتن
--  او پزشکی ندارد. صفحه‌ی ویزیت و صفحه‌ی نوار مغز هم نام او را
--  در متن داشتند.
--
--  تبلیغ یک خدمت درمانی که پزشکی برای انجامش نیست، برای بیمار
--  گمراه‌کننده است. پس بخش غیرفعال و صفحه‌ها پیش‌نویس می‌شوند.
--
--  حذف نمی‌شوند چون متنشان نوشته شده و اگر متخصص مغز و اعصاب
--  تازه‌ای اضافه شود، برگرداندنشان دو خط SQL است:
--
--    UPDATE clinics SET is_active = 1 WHERE slug = 'neurology';
--    UPDATE pages SET status = 'published'
--      WHERE path IN ('/service/ویزیت-متخصص-مغز-و-اعصاب/',
--                     '/service/نوار-مغز/');
-- ------------------------------------------------------------
UPDATE clinics SET is_active = 0 WHERE slug = 'neurology';

UPDATE pages SET status = 'draft'
 WHERE path IN ('/service/ویزیت-متخصص-مغز-و-اعصاب/', '/service/نوار-مغز/');

-- نام پزشک از متن برداشته می‌شود تا حتی اگر روزی صفحه دوباره
-- منتشر شود، نام کسی که اینجا نیست روی سایت نماند.
UPDATE pages
   SET body = REPLACE(body,
       '<p>این ویزیت توسط <strong>دکتر مهدی شفیعی ثابت</strong>، متخصص بیماری‌های مغز و اعصاب، انجام می‌شود.</p>',
       '')
 WHERE path = '/service/ویزیت-متخصص-مغز-و-اعصاب/';

UPDATE pages
   SET body = REPLACE(body,
       '<p>نوار مغز در بخش مغز و اعصاب و زیر نظر <strong>دکتر مهدی شفیعی ثابت</strong>، متخصص بیماری‌های مغز و اعصاب، انجام و تفسیر می‌شود.</p>',
       '')
 WHERE path = '/service/نوار-مغز/';

-- ------------------------------------------------------------
--  پاک‌سازی تگ‌های یتیم
--  اگر رسانه‌ای به بخش یا صفحه‌ی حذف‌شده‌ای تگ خورده بود.
-- ------------------------------------------------------------
DELETE FROM media_tag
 WHERE entity_type = 'doctor' AND entity_id NOT IN (SELECT id FROM doctors);
DELETE FROM media_tag
 WHERE entity_type = 'clinic' AND entity_id NOT IN (SELECT id FROM clinics);
DELETE FROM media_tag
 WHERE entity_type = 'page'   AND entity_id NOT IN (SELECT id FROM pages);
